<h2>1. Information we collect</h2>

<p><strong>Information you give us</strong></p>

<ul>
    <li>
        <strong>Account details:</strong>
        Name, username, email address, phone number, password
        (stored using secure hashing), and optionally gender and
        date of birth. If you sign in with Google or Apple, we receive
        your name and email address from that provider. We never
        receive your Google or Apple password.
    </li>

    <li>
        <strong>Delivery details:</strong>
        Shipping addresses and phone numbers you provide when
        placing orders.
    </li>

    <li>
        <strong>Orders and payments:</strong>
        Items ordered, quantities, amounts, order status and payment
        references. Card and bank payments are processed by Paystack.
        We do not receive or store your full card number, PIN or CVV.
    </li>

    <li>
        <strong>Refund bank account (optional):</strong>
        Bank name, account name and account number, where you provide
        these details for receiving refunds. Account information is
        stored using appropriate security measures, including
        encryption where implemented.
    </li>

    <li>
        <strong>Photos and messages:</strong>
        Profile pictures and photos or messages you send through
        customer support chat. We access only the photos you choose
        to select or take.
    </li>

    <li>
        <strong>Reviews:</strong>
        Ratings and comments you post about products and, if you
        choose to provide it, your city. Reviews may be displayed
        publicly within the app or on our website.
    </li>
</ul>

<p><strong>Information collected automatically</strong></p>

<ul>
    <li>
        Device and app information needed to operate the application
        and provide notifications, including push notification token,
        device platform, app version and IP address.
    </li>

    <li>
        Usage and diagnostic information about how the app is used,
        which may be collected through Google Firebase services,
        including Firebase Analytics and Firebase Cloud Messaging.
    </li>
</ul>

<p>
    <strong>Location (optional):</strong>
    When you add a delivery address, you may select "Use my location"
    to identify your delivery location on a map. With your permission,
    the app accesses your device's precise location while you are
    using the app to help identify the delivery point. We save the
    selected map location together with the delivery address.
    We do not track your location in the background. You may also
    enter your address manually or adjust the map location yourself.
    You can disable location access through your device settings.
</p>

<p>
    <strong>Camera (optional):</strong>
    When you use Scan &amp; Shop in a Gozak Mart store, the app uses
    your camera to scan product barcodes and the store's QR code.
    Camera access is used while the scanner is active. Scanner images
    are processed on your device and are not saved or uploaded by us
    as photos or videos. We may record the store associated with
    your order to enable order processing, packing and delivery.
</p>

<p>
    The app does not access your contacts, SMS messages, call logs
    or microphone.
</p>

